#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Idempotent iOS bootstrap for kira.

Runs on the macOS GitHub runner before `flutter build ios`. It patches the
checkout in the runner workspace only (nothing is committed), so the repo can
stay as-is:

  1. create ios/Podfile (CocoaPods integration, platform 16.0)
  2. wire Pods xcconfig into ios/Flutter/{Debug,Release}.xcconfig
  3. add photo-library / ATS / local-network keys to ios/Runner/Info.plist
  4. raise IPHONEOS_DEPLOYMENT_TARGET to 16.0
  5. make the in-app update source configurable (UPDATE_REPO / UPDATE_API_ROOT)
  6. iOS album permission + non-Android display-mode guard in Dart

Every step checks for the already-patched state first, so running it on an
already patched checkout is a no-op.
"""

import os
import plistlib
import re
import sys
from pathlib import Path

ROOT = Path.cwd()
TARGET = (os.environ.get("DEPLOYMENT_TARGET") or "16.0").strip() or "16.0"
DEFAULT_REPO = (os.environ.get("UPDATE_REPO") or "").strip() or "qingchenye/kira"


def warn(msg):
    print("::warning::" + msg)


def info(msg):
    print(msg)


PODFILE = """# Generated by scripts/ios_prepare.py (kira iOS bootstrap).
# Flutter pods; keep in sync with flutter_tools/templates/cocoapods/Podfile-ios.

platform :ios, '__TARGET__'

ENV['COCOAPODS_DISABLE_STATS'] = 'true'

project 'Runner', {
  'Debug' => :debug,
  'Profile' => :release,
  'Release' => :release,
}

def flutter_root
  generated_xcode_build_settings_path = File.expand_path(File.join('..', 'Flutter', 'Generated.xcconfig'), __FILE__)
  unless File.exist?(generated_xcode_build_settings_path)
    raise "#{generated_xcode_build_settings_path} must exist. If you're running pod install manually, make sure flutter pub get is executed first"
  end

  File.foreach(generated_xcode_build_settings_path) do |line|
    matches = line.match(/FLUTTER_ROOT\\=(.*)/)
    return matches[1].strip if matches
  end
  raise "FLUTTER_ROOT not found in #{generated_xcode_build_settings_path}. Try deleting Generated.xcconfig, then run flutter pub get"
end

require File.expand_path(File.join('packages', 'flutter_tools', 'bin', 'podhelper'), flutter_root)

flutter_ios_podfile_setup

target 'Runner' do
  use_frameworks!

  flutter_install_all_ios_pods File.dirname(File.realpath(__FILE__))
  target 'RunnerTests' do
    inherit! :search_paths
  end
end

post_install do |installer|
  installer.pods_project.targets.each do |target|
    flutter_additional_ios_build_settings(target)
  end
end
"""


def ensure_podfile():
    path = ROOT / "ios" / "Podfile"
    content = path.read_text(encoding="utf-8") if path.exists() else ""
    if not content.strip():
        path.write_text(PODFILE.replace("__TARGET__", TARGET), encoding="utf-8", newline="\n")
        info("created ios/Podfile (platform :ios, '%s')" % TARGET)
        return
    if re.search(r"^platform\s+:ios", content, re.M):
        updated = re.sub(
            r"^platform\s+:ios\s*,\s*'[^']*'",
            "platform :ios, '%s'" % TARGET,
            content,
            count=1,
            flags=re.M,
        )
    else:
        updated = "platform :ios, '%s'\n\n%s" % (TARGET, content)
    if updated != content:
        path.write_text(updated, encoding="utf-8", newline="\n")
        info("ios/Podfile platform -> %s" % TARGET)


def ensure_xcconfig(name, pod_xcconfig):
    path = ROOT / "ios" / "Flutter" / name
    include = '#include? "Pods/Target Support Files/Pods-Runner/%s"' % pod_xcconfig
    content = path.read_text(encoding="utf-8") if path.exists() else '#include "Generated.xcconfig"\n'
    if include in content:
        return
    content = include + "\n" + content
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    info("patched ios/Flutter/%s" % name)


def ensure_info_plist():
    path = ROOT / "ios" / "Runner" / "Info.plist"
    if not path.exists():
        warn("ios/Runner/Info.plist not found, skip")
        return
    with path.open("rb") as handle:
        data = plistlib.load(handle)

    changed = False
    defaults = {
        "NSPhotoLibraryAddUsageDescription": "保存漫画或轻小说插图到相册需要访问照片库。",
        "NSPhotoLibraryUsageDescription": "保存图片到「kira」相册需要访问照片库。",
        "NSLocalNetworkUsageDescription": "连接局域网内的 WebDAV 备份服务器或代理节点需要访问本地网络。",
    }
    for key, value in defaults.items():
        if key not in data:
            data[key] = value
            changed = True

    ats = data.setdefault("NSAppTransportSecurity", {})
    if not ats.get("NSAllowsArbitraryLoads"):
        ats["NSAllowsArbitraryLoads"] = True
        changed = True

    if changed:
        with path.open("wb") as handle:
            plistlib.dump(data, handle)
        info("patched ios/Runner/Info.plist")


def ensure_deployment_target():
    path = ROOT / "ios" / "Runner.xcodeproj" / "project.pbxproj"
    if not path.exists():
        warn("ios/Runner.xcodeproj/project.pbxproj not found, skip")
        return
    text = path.read_text(encoding="utf-8")
    pattern = r"IPHONEOS_DEPLOYMENT_TARGET = \d+(?:\.\d+)?;"
    if not re.search(pattern, text):
        warn("project.pbxproj: IPHONEOS_DEPLOYMENT_TARGET not found")
        return
    updated = re.sub(pattern, "IPHONEOS_DEPLOYMENT_TARGET = %s;" % TARGET, text)
    if updated != text:
        path.write_text(updated, encoding="utf-8", newline="\n")
        info("project.pbxproj deployment target -> %s" % TARGET)


def patch_text(relative_path, replacements, marker):
    path = ROOT / relative_path
    if not path.exists():
        warn("%s not found, skip" % relative_path)
        return
    text = path.read_text(encoding="utf-8")
    if marker in text:
        return
    updated = text
    for pattern, replacement in replacements:
        updated = re.sub(pattern, replacement, updated, count=1)
    if updated == text:
        warn("%s: expected pattern not found, skip" % relative_path)
        return
    path.write_text(updated, encoding="utf-8", newline="\n")
    info("patched %s" % relative_path)


APP_UPDATE_NEW = (
    "static const _updateRepo = String.fromEnvironment(\n"
    "    'UPDATE_REPO',\n"
    "    defaultValue: '%s',\n"
    "  );\n\n"
    "  static const _updateApiRoot = String.fromEnvironment(\n"
    "    'UPDATE_API_ROOT',\n"
    "    defaultValue: 'https://api.github.com',\n"
    "  );\n\n"
    "  static String get _latestReleaseUrl =>\n"
    "      '$_updateApiRoot/repos/$_updateRepo/releases/latest';\n"
    "  static String get _ciReleaseUrl =>\n"
    "      '$_updateApiRoot/repos/$_updateRepo/releases/tags/CI';"
) % DEFAULT_REPO


def patch_app_update():
    patch_text(
        "lib/utils/app_update.dart",
        [
            (
                r"static const _latestReleaseUrl =\s*'[^']*';\s*\n\s*static const _ciReleaseUrl =\s*'[^']*';",
                APP_UPDATE_NEW,
            )
        ],
        marker="_updateRepo",
    )


def patch_reader():
    patch_text(
        "lib/pages/reader/reader_image_viewer.dart",
        [
            (
                r"final hasAccess = await Gal\.hasAccess\(\);",
                "final hasAccess = await Gal.hasAccess(toAlbum: Platform.isIOS);",
            ),
            (
                r"if \(!hasAccess && !await Gal\.requestAccess\(\)\)",
                "if (!hasAccess && !await Gal.requestAccess(toAlbum: Platform.isIOS))",
            ),
        ],
        marker="toAlbum: Platform.isIOS",
    )


def patch_display_mode():
    patch_text(
        "lib/utils/display_mode_preference.dart",
        [
            (
                r"(static Future<List<int>> loadRefreshRates\(\) async \{)",
                r"\1\n    if (!isSupportedPlatform) return _candidateRefreshRates.toList();",
            ),
            (
                r"(static Future<int\?> activeRefreshRate\(\) async \{)",
                r"\1\n    if (!isSupportedPlatform) return null;",
            ),
        ],
        marker="isSupportedPlatform) return _candidateRefreshRates",
    )


APP_DELEGATE_OLD = """    let messenger = engineBridge.engine.binaryMessenger
    let channel = FlutterMethodChannel(
      name: "io.github.caolib.kira/app_icon",
      binaryMessenger: messenger
    )"""

APP_DELEGATE_NEW = """    guard let registrar = engineBridge.pluginRegistry.registrar(forPlugin: "KiraAppIcon") else {
      return
    }
    let channel = FlutterMethodChannel(
      name: "io.github.caolib.kira/app_icon",
      binaryMessenger: registrar.messenger()
    )"""


def patch_app_delegate():
    """Flutter 3.44 的 FlutterImplicitEngineBridge 已没有 .engine 成员。"""
    path = ROOT / "ios" / "Runner" / "AppDelegate.swift"
    if not path.exists():
        warn("ios/Runner/AppDelegate.swift not found, skip")
        return
    text = path.read_text(encoding="utf-8")
    if "registrar.messenger()" in text:
        return
    if APP_DELEGATE_OLD not in text:
        warn("AppDelegate.swift: expected messenger pattern not found, skip")
        return
    path.write_text(text.replace(APP_DELEGATE_OLD, APP_DELEGATE_NEW), encoding="utf-8", newline="\n")
    info("patched ios/Runner/AppDelegate.swift")


def main():
    if not (ROOT / "pubspec.yaml").exists():
        sys.exit("not a kira checkout: %s" % ROOT)

    ensure_podfile()
    ensure_xcconfig("Debug.xcconfig", "Pods-Runner.debug.xcconfig")
    ensure_xcconfig("Release.xcconfig", "Pods-Runner.release.xcconfig")
    ensure_info_plist()
    ensure_deployment_target()
    patch_app_update()
    patch_reader()
    patch_display_mode()
    patch_app_delegate()
    info("iOS bootstrap done (target iOS %s, update repo %s)" % (TARGET, DEFAULT_REPO))


if __name__ == "__main__":
    main()
